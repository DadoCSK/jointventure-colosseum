import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import anchor from '@coral-xyz/anchor';
import {Keypair,PublicKey,SystemProgram,TransactionInstruction} from '@solana/web3.js';
import {chainClient} from './chain-client.mjs';
const {AnchorProvider,Program,Wallet}=anchor;
const {connection,program,project,authority}=await chainClient({local:true});
const digest=createHash('sha256').update(fs.readFileSync('tests/fixtures/integrity-test.txt')).digest();
const derive=(id,projectKey=project)=>PublicKey.findProgramAddressSync([Buffer.from('document'),projectKey.toBuffer(),Buffer.from(id)],program.programId);
const accounts=id=>({authority:authority.publicKey,project,documentRecord:derive(id)[0],systemProgram:SystemProgram.programId});
const record=(id,name='Harmless integrity test fixture',hash=digest)=>program.methods.recordDocument(id,name,Buffer.from(hash)).accountsStrict(accounts(id)).rpc();
const projectBefore=(await connection.getAccountInfo(project)).data;
const testId='integrity-test-'+Date.now().toString(36);
await record(testId);
const [pda,bump]=derive(testId);
const state=await program.account.documentRecord.fetch(pda);
assert.ok(state.project.equals(project));assert.ok(state.authority.equals(authority.publicKey));
assert.equal(state.documentId,testId);assert.equal(state.documentName,'Harmless integrity test fixture');
assert.deepEqual(state.sha256Hash,Array.from(digest));assert.equal(state.bump,bump);assert.ok(state.createdAt.toNumber()>0);
assert.deepEqual((await connection.getAccountInfo(project)).data,projectBefore);
const recordBefore=(await connection.getAccountInfo(pda)).data;
await assert.rejects(record(testId));
assert.deepEqual((await connection.getAccountInfo(pda)).data,recordBefore);
const stranger=Keypair.generate();
await connection.confirmTransaction(await connection.requestAirdrop(stranger.publicKey,1e9),'confirmed');
const strangerProgram=new Program(program.idl,new AnchorProvider(connection,new Wallet(stranger),{commitment:'confirmed'}));
await assert.rejects(strangerProgram.methods.recordDocument('unauthorized-test','Harmless test',digest).accountsStrict({...accounts('unauthorized-test'),authority:stranger.publicKey}).rpc(),/Unauthorized/);
assert.equal(await connection.getAccountInfo(derive('unauthorized-test')[0]),null);
await assert.rejects(program.methods.recordDocument('wrong-project','Harmless test',digest).accountsStrict({...accounts('wrong-project'),project:SystemProgram.programId}).rpc());
assert.equal(await connection.getAccountInfo(derive('wrong-project')[0]),null);
await assert.rejects(record(''),/InvalidId/);
await assert.rejects(program.methods.recordDocument('x'.repeat(33),'Harmless test',digest).accountsStrict(accounts('oversized-test')).rpc());
await assert.rejects(record('UPPERCASE'),/InvalidId/);
await assert.rejects(record('invalid-name',' '),/InvalidName/);
await assert.rejects(record('long-name','x'.repeat(65)),/InvalidName/);
await assert.rejects(record('invalid-hash','Harmless test',digest.slice(0,31)));
await assert.rejects(record('invalid-hash','Harmless test',[...digest,1]));
const ix=await program.methods.recordDocument('short-wire','Harmless test',digest).accountsStrict(accounts('short-wire')).instruction();
const malformed=new TransactionInstruction({...ix,data:ix.data.subarray(0,ix.data.length-1)});
await assert.rejects(program.provider.sendAndConfirm(new (await import('@solana/web3.js')).Transaction().add(malformed)),/InstructionDidNotDeserialize/);
assert.equal(await connection.getAccountInfo(derive('short-wire')[0]),null);
console.log('PASS: document creation, exact SHA-256 bytes, project/authority reference, timestamp, bump, immutability, duplicates, unauthorized/invalid project, ID/name limits, and short hashes');
