import assert from 'node:assert/strict';
import anchor from '@coral-xyz/anchor';
const {AnchorProvider, Program, Wallet, BN}=anchor;
import { Keypair, PublicKey, SystemProgram } from '@solana/web3.js';
import { getAccount, createMint, getOrCreateAssociatedTokenAccount, mintTo, TOKEN_PROGRAM_ID } from '@solana/spl-token';
import { chainClient } from './chain-client.mjs';

const {connection,authority,program,project,vault}=await chainClient({local:true});
const state=await program.account.project.fetch(project);
const investor=Keypair.generate();
await connection.confirmTransaction(await connection.requestAirdrop(investor.publicKey,1e9),'confirmed');
const source=await getOrCreateAssociatedTokenAccount(connection,authority,state.acceptedMint,investor.publicKey);
await mintTo(connection,authority,state.acceptedMint,source.address,authority,1_000_000_000n);
const [position]=PublicKey.findProgramAddressSync([Buffer.from('position'),project.toBuffer(),investor.publicKey.toBuffer()],program.programId);
const investorProgram=new Program(program.idl,new AnchorProvider(connection,new Wallet(investor),{commitment:'confirmed'}));
const accounts={investor:investor.publicKey,project,mint:state.acceptedMint,vault,source:source.address,position,tokenProgram:TOKEN_PROGRAM_ID,systemProgram:SystemProgram.programId};
const finance=(amount,nonce,override={})=>investorProgram.methods.finance(new BN(amount),new BN(nonce)).accountsStrict({...accounts,...override}).rpc();
await assert.rejects(investorProgram.methods.setFinancingEnabled(true).accountsStrict({authority:investor.publicKey,project}).rpc(),/Unauthorized/);
await assert.rejects(finance(10,0),/FinancingDisabled/);
assert.equal(await connection.getAccountInfo(position),null);
await program.methods.setFinancingEnabled(true).accountsStrict({authority:authority.publicKey,project}).rpc();
await assert.rejects(finance(0,0),/InvalidAmount/);
assert.equal(await connection.getAccountInfo(position),null);
const wrongMint=await createMint(connection,authority,authority.publicKey,null,6);
await assert.rejects(finance(10,0,{mint:wrongMint}),/ConstraintAddress/);
const otherSource=await getOrCreateAssociatedTokenAccount(connection,authority,state.acceptedMint,authority.publicKey);
await assert.rejects(finance(10,0,{source:otherSource.address}),/ConstraintTokenOwner/);
await assert.rejects(finance(10,0,{vault:otherSource.address}),/ConstraintSeeds/);
await assert.rejects(finance(10,0,{position:Keypair.generate().publicKey}),/ConstraintSeeds/);
await assert.rejects(finance(1_000_000_001,0));
assert.equal(await connection.getAccountInfo(position),null);
const before=(await program.account.project.fetch(project)).totalFinancedUnits;
const vaultBefore=(await getAccount(connection,vault)).amount;
await finance(125_500_000,0);
await assert.rejects(finance(125_500_000,0),/StaleNonce/);
await finance(500_000,1);
const record=await program.account.position.fetch(position);
assert.ok(record.project.equals(project));
assert.ok(record.investor.equals(investor.publicKey));
assert.equal(record.contributedUnits.toString(),'126000000');
assert.equal(record.nextNonce.toString(),'2');
assert.equal((await program.account.project.fetch(project)).totalFinancedUnits.sub(before).toString(),'126000000');
assert.equal((await getAccount(connection,vault)).amount-vaultBefore,126_000_000n);
assert.equal((await getAccount(connection,source.address)).amount,874_000_000n);
await program.methods.setFinancingEnabled(false).accountsStrict({authority:authority.publicKey,project}).rpc();
await assert.rejects(finance(1,2),/FinancingDisabled/);
assert.equal((await program.account.position.fetch(position)).nextNonce.toString(),'2');
console.log('PASS: authority pause control, disabled/zero/insufficient amounts, wrong mint/owner/vault/position, successful deposits, nonce replay protection, exact totals, and atomic failures');
